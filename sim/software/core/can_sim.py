"""Simulated CAN bus (python-pcan style) for the Lunabotics rover sim.

Speaks the exact same extended-ID frames as Rover/UMRS/src/main.rs:

TX (rover computer -> bus, from main.rs):
  Velocity command : id = 0x02050080 | (device_id & 0x3F)
                     payload = f32-le rpm, [0,0,0], mode byte 1
                     (build_velocity_can_id: device_type 2<<24,
                      manufacturer 5<<16, api_class 1<<10, api_index 2<<6)
  Sabertooth cmd   : id = 0x00100001
                     payload = i16-le act_speed, i16-le depo_speed, 0,0,0,0

RX (bus -> rover computer, generated by this simulator):
  Wheel RPM report : id = 0x02051800 | (device_id & 0x3F)
                     (manufacturer 5, api_class 6, api_index 1)
                     payload = f32-le measured rpm
  Linear position  : same id family with api_index 2 (device 1)
                     payload = f32-le position
  Sabertooth ADC   : id = 0x00200001
                     payload = u16-le adc, f32-le depo linear-encoder cm
  IMU              : id = 0x00200002
                     payload = i16-le yaw, pitch, roll (degrees * 100)

The Rust coordinator never touches this module directly; it opens
socketcan "can0". For now the python sim uses this class internally and
optionally bridges to a real vcan through python-can if installed.
"""

import struct


# ---- TX ids (coordinator -> devices) --------------------------------
def velocity_cmd_id(device_id: int) -> int:
    return (2 << 24) | (5 << 16) | (1 << 10) | (2 << 6) | (device_id & 0x3F)


SABERTOOTH_CMD_ID = 0x00100001

# ---- RX ids (devices -> coordinator) --------------------------------
def rpm_report_id(device_id: int) -> int:
    """manufacturer 5, api_class 6, api_index 1."""
    return (2 << 24) | (5 << 16) | (6 << 10) | (1 << 6) | (device_id & 0x3F)


LINEAR_POS_ID = (2 << 24) | (5 << 16) | (6 << 10) | (2 << 6) | 1
SABERTOOTH_TELEM_ID = 0x00200001
IMU_TELEM_ID = 0x00200002


class CanFrame:
    __slots__ = ("can_id", "data")

    def __init__(self, can_id: int, data: bytes):
        self.can_id = can_id
        self.data = bytes(data[:8]).ljust(8, b"\x00")

    def __repr__(self):
        return f"CanFrame(0x{self.can_id:08X}, {self.data.hex()})"


class SimCanBus:
    """In-process CAN bus. Coordinator-side code writes frames here;
    the simulated devices consume them and produce telemetry frames."""

    def __init__(self):
        self.tx_log = []          # frames received FROM the rover computer
        self.rx_queue = []        # frames queued TO the rover computer

    # --- called by UMRS/coordinator side -----------------------------
    def send_frame(self, frame: CanFrame):
        self.tx_log.append(frame)

    def recv_frame(self):
        return self.rx_queue.pop(0) if self.rx_queue else None

    # --- called by simulated device side ------------------------------
    def push_telemetry(self, frame: CanFrame):
        self.rx_queue.append(frame)

    # --- helpers -------------------------------------------------------
    @staticmethod
    def make_rpm_frame(device_id: int, rpm: float) -> CanFrame:
        return CanFrame(rpm_report_id(device_id), struct.pack("<f", rpm))

    @staticmethod
    def make_linear_pos_frame(pos: float) -> CanFrame:
        return CanFrame(LINEAR_POS_ID, struct.pack("<f", pos))

    @staticmethod
    def make_sabertooth_frame(adc: int, depo_cm: float) -> CanFrame:
        return CanFrame(SABERTOOTH_TELEM_ID,
                        struct.pack("<Hf", int(adc) & 0xFFFF, depo_cm))

    @staticmethod
    def make_imu_frame(yaw_deg: float, pitch_deg: float = 0.0,
                       roll_deg: float = 0.0) -> CanFrame:
        return CanFrame(IMU_TELEM_ID, struct.pack(
            "<hhh",
            int(round(max(-180.0, min(180.0, yaw_deg)) * 100)),
            int(round(max(-90.0, min(90.0, pitch_deg)) * 100)),
            int(round(max(-180.0, min(180.0, roll_deg)) * 100)),
        ))

    @staticmethod
    def parse_velocity_cmd(frame: CanFrame):
        """Return (device_id, rpm) if frame is a velocity command."""
        cid = frame.can_id
        base = (2 << 24) | (5 << 16) | (1 << 10) | (2 << 6)
        if cid & 0xFFFFFFC0 == base:
            return cid & 0x3F, struct.unpack("<f", frame.data[0:4])[0]
        return None

    @staticmethod
    def parse_sabertooth_cmd(frame: CanFrame):
        if frame.can_id == SABERTOOTH_CMD_ID:
            act = struct.unpack("<h", frame.data[0:2])[0]
            depo = struct.unpack("<h", frame.data[2:4])[0]
            return act, depo
        return None
